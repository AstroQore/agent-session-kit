    /// Scan cursors keyed by file name. Directory enumeration reports
    /// `/private/var/…` while the fixtures build `/var/…`, so the tests
    /// compare on the file name rather than on a hashed absolute path.
    private func cursors() throws -> [String: Int64] {
        var handle: OpaquePointer?
        guard sqlite3_open_v2(databaseURL.path, &handle, SQLITE_OPEN_READONLY, nil) == SQLITE_OK,
              let handle
        else { throw CocoaError(.fileReadUnknown) }
        defer { sqlite3_close_v2(handle) }
        var statement: OpaquePointer?
        guard sqlite3_prepare_v2(
            handle, "SELECT path, mtime_ns, size FROM session_files", -1, &statement, nil
        ) == SQLITE_OK, let statement else { throw CocoaError(.fileReadUnknown) }
        defer { sqlite3_finalize(statement) }
        var out: [String: Int64] = [:]
        while sqlite3_step(statement) == SQLITE_ROW {
            guard let raw = sqlite3_column_text(statement, 0) else { continue }
            let name = URL(fileURLWithPath: String(cString: raw)).lastPathComponent
            out[name] = sqlite3_column_int64(statement, 1) &+ sqlite3_column_int64(statement, 2)
        }
        return out
    }

