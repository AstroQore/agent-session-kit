    func testTurningBodyIndexingOffDropsPreviouslyIndexedBodies() async throws {
        try writeClaudeSession()
        let store = try SessionIndexStore(url: databaseURL)
        let enabled = SwitchBox(value: true)
        let service = SessionIndexService(
            homeDirectory: home.path,
            store: store,
            registry: SessionProviderRegistry.standard(homeDirectory: home.path),
            bodyIndexing: { enabled.value }
        )

        await service.refreshIndex()
        let indexed = try await store.messageCount()
        XCTAssertGreaterThan(indexed, 0)

        enabled.value = false
        let modeChange = await service.refreshIndexCandidates([], budget: Self.budget)
        XCTAssertTrue(modeChange.modeChanged)
        XCTAssertEqual(modeChange.written, 0)
        let unchanged = await service.refreshIndexCandidates([], budget: Self.budget)
        XCTAssertFalse(unchanged.modeChanged)

        let dropped = try await store.messageCount()
        let sessions = try await store.sessionCount()
        XCTAssertEqual(dropped, 0)
        XCTAssertEqual(sessions, 1)

        // Switching back on has to backfill: the file's fingerprint never
        // moved, so only the mode change can trigger a re-read.
        enabled.value = true
        await service.refreshIndex()

        let backfilled = try await store.messageCount()
        XCTAssertEqual(backfilled, indexed)
        let hits = try await service.search("indexing 中文")
        XCTAssertEqual(hits.count, 1)
    }

